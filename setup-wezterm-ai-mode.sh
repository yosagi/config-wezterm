#!/usr/bin/env bash
# Wezterm AI Helper Mode セットアップスクリプト
#
# codex 起動時に自動的に claude_mode キーテーブルに切り替える
# ラッパースクリプトを ~/.local/bin に配置する
#
# 注: Claude Code は statusline.sh 経由で OSC シーケンスを送るため
#     ラッパー不要。このスクリプトは codex 用のみ。
#
# 使い方:
#   ./setup-wezterm-ai-mode.sh
#
# アンインストール:
#   ./setup-wezterm-ai-mode.sh --uninstall

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${HOME}/.local/bin"
BASHRC="${HOME}/.bashrc"

# 色付き出力
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
RED='\033[0;31m'
NC='\033[0m'

info()  { echo -e "${GREEN}$*${NC}"; }
warn()  { echo -e "${YELLOW}$*${NC}"; }
error() { echo -e "${RED}$*${NC}" >&2; }

# ラッパースクリプトを作成
# $1: コマンド名 (codex)
# $2: 実際の実行パス
create_wrapper() {
    local name="$1"
    local real_path="$2"
    local wrapper_path="${BIN_DIR}/${name}"

    cat > "$wrapper_path" <<WRAPPER_EOF
#!/bin/sh
# ${name} launcher with wezterm AI helper mode support
# Generated by setup-wezterm-ai-mode.sh

# wezterm 環境の場合、AI helper mode を設定
if [ -n "\$WEZTERM_PANE" ]; then
    printf '\033]1337;SetUserVar=%s=%s\007' 'WEZTERM_AI_HELPER' "\$(printf '%s' '${name}' | base64)"
fi

# 本体を実行
exec "${real_path}" "\$@"
WRAPPER_EOF

    chmod +x "$wrapper_path"
    info "  Created: $wrapper_path -> $real_path"
}

# 実際のコマンドパスを探す（ラッパーを除外）
find_real_command() {
    local name="$1"
    local path=""

    # ~/.local/bin を除外した PATH で検索
    local filtered_path
    filtered_path=$(echo "$PATH" | tr ':' '\n' | grep -v "^${BIN_DIR}\$" | tr '\n' ':' | sed 's/:$//')

    path=$(PATH="$filtered_path" command -v "$name" 2>/dev/null || true)

    echo "$path"
}

# インストール
install() {
    echo -e "${BLUE}╔════════════════════════════════════════════════════════════════╗${NC}"
    echo -e "${BLUE}║      Wezterm AI Helper Mode - セットアップ                    ║${NC}"
    echo -e "${BLUE}╚════════════════════════════════════════════════════════════════╝${NC}"
    echo

    # ステップ1: ~/.local/bin ディレクトリの確認
    echo -e "${GREEN}[1/3] ディレクトリ確認${NC}"
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

    if [ ! -d "$BIN_DIR" ]; then
        info "Creating $BIN_DIR ..."
        mkdir -p "$BIN_DIR"
    else
        info "✓ $BIN_DIR exists"
    fi

    # PATH に含まれているか確認
    if ! echo "$PATH" | tr ':' '\n' | grep -q "^${BIN_DIR}\$"; then
        warn "Warning: $BIN_DIR is not in PATH"
        warn "Add to your shell config: export PATH=\"\$HOME/.local/bin:\$PATH\""
    else
        info "✓ $BIN_DIR is in PATH"
    fi
    echo

    # ステップ2: codex ラッパーのセットアップ
    echo -e "${GREEN}[2/3] Codex ラッパー作成${NC}"
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

    local codex_real
    codex_real=$(find_real_command codex)

    if [ -n "$codex_real" ]; then
        if [ -f "${BIN_DIR}/codex" ]; then
            warn "  Existing wrapper found, overwriting..."
        fi
        create_wrapper "codex" "$codex_real"
    else
        warn "  codex command not found, skipping"
    fi
    echo

    # ステップ3: bash prompt integration
    echo -e "${GREEN}[3/3] Bash プロンプト設定${NC}"
    echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

    local integration_marker="wezterm-prompt-integration.bash"

    if grep -qF "$integration_marker" "$BASHRC" 2>/dev/null; then
        info "✓ 既に .bashrc に prompt integration が設定されています"
    else
        echo "~/.bashrc に wezterm prompt integration を追加しています..."
        cat >> "$BASHRC" << 'EOF'

# Wezterm AI helper prompt integration
if [[ -f "$HOME/.config/wezterm/wezterm-prompt-integration.bash" ]]; then
    source "$HOME/.config/wezterm/wezterm-prompt-integration.bash"
fi
EOF
        info "✓ .bashrc に設定を追加しました"
    fi
    echo

    # 完了メッセージ
    echo -e "${BLUE}═══════════════════════════════════════════════════════════════${NC}"
    info "✓ セットアップが完了しました！"
    echo
    echo "次のステップ:"
    echo "  1. 新しいシェルを起動するか、以下を実行:"
    echo -e "     ${BLUE}source ~/.bashrc && hash -r${NC}"
    echo
    echo "  2. wezterm で codex を実行すると自動的に AI Mode に切り替わります"
    echo
    echo -e "${YELLOW}Claude Code について:${NC}"
    echo "  Claude Code は statusline.sh 経由で OSC シーケンスを送るため"
    echo "  ラッパー不要です。直接 claude コマンドで起動できます。"
    echo -e "${BLUE}═══════════════════════════════════════════════════════════════${NC}"
}

# アンインストール
uninstall() {
    echo -e "${BLUE}=== Uninstalling Wezterm AI Helper Mode ===${NC}"
    echo

    # codex ラッパーのみ削除（claude-code は別管理）
    local wrapper="${BIN_DIR}/codex"
    if [ -f "$wrapper" ]; then
        rm "$wrapper"
        info "Removed: $wrapper"
    fi

    echo
    info "アンインストール完了"
    echo "必要に応じて ~/.bashrc の alias/関数を復元してください"
}

# メイン
case "${1:-}" in
    --uninstall|-u)
        uninstall
        ;;
    --help|-h)
        echo "Usage: $0 [--uninstall]"
        echo
        echo "Setup wezterm AI helper mode for codex."
        echo "Creates wrapper script in ~/.local/bin/"
        echo
        echo "Note: Claude Code uses statusline.sh for OSC sequences,"
        echo "      so no wrapper is needed."
        ;;
    *)
        install
        ;;
esac
